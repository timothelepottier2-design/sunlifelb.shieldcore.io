                        if v.title and v.spawned and v.entity and DoesEntityExist(v.entity) then
                            local headPos = GetEntityCoords(v.entity)
                            DrawNpcText3D(headPos.x, headPos.y, headPos.z, v.title)
                        end
                    end
                    if IsControlJustReleased(1, 38) then
                        v.action()
                    end
                end
            end
        end

        if near_npc then
            Wait(0)
        else
            Wait(2500)
        end
    end
end)

